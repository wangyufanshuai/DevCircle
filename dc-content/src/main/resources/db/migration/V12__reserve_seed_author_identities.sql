UPDATE post
SET author_id = CASE
    WHEN id BETWEEN 1001 AND 1100 THEN 9000000001 + MOD(id - 1001, 10)
    WHEN id BETWEEN 2001 AND 2040 THEN 9000000001 + MOD(id - 2001 + 3, 10)
    WHEN id BETWEEN 3001 AND 3040 THEN 9000000001 + MOD(id - 3001 + 6, 10)
    ELSE author_id
END
WHERE id BETWEEN 1001 AND 1100
   OR id BETWEEN 2001 AND 2040
   OR id BETWEEN 3001 AND 3040;
